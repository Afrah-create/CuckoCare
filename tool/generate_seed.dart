import 'dart:convert';
import 'dart:io';

/// Reads vaccination JSON and writes supabase/seed.sql for programmes tables.
void main() {
  final path = 'assets/seed/uganda_poultry_vaccination_schedule.json';
  final file = File(path);
  if (!file.existsSync()) {
    stderr.writeln('Missing $path');
    exit(1);
  }
  final json = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;

  final buffer = StringBuffer()
    ..writeln('-- Generated by tool/generate_seed.dart');

  if (json.containsKey('programs')) {
    _emitLegacyPrograms(json, buffer);
  } else if (json.containsKey('programmes')) {
    _emitProgrammesArray(json, buffer);
  } else {
    stderr.writeln(
      'Expected "programmes" or "programs.broiler.steps" / "programs.layer.steps"',
    );
    exit(1);
  }

  final vetSeed = File('supabase/seed_dev_vets.sql');
  if (vetSeed.existsSync()) {
    buffer
      ..writeln()
      ..writeln(vetSeed.readAsStringSync().trim());
  }

  File('supabase/seed.sql').writeAsStringSync(buffer.toString());
  stdout.writeln('Wrote supabase/seed.sql');
}

void _emitLegacyPrograms(Map<String, dynamic> json, StringBuffer buffer) {
  final programs = json['programs'] as Map<String, dynamic>?;
  if (programs == null) {
    stderr.writeln('Missing programs object');
    exit(1);
  }
  for (final key in ['broiler', 'layer']) {
    final p = programs[key] as Map<String, dynamic>?;
    if (p == null || p['steps'] == null) {
      stderr.writeln('Missing programs.$key.steps');
      exit(1);
    }
  }
  if (programs['layer']?['recurring'] == null) {
    stderr.writeln('Missing programs.layer.recurring');
    exit(1);
  }
  buffer.writeln('-- TODO: map legacy programs.* layout to SQL inserts');
}

void _emitProgrammesArray(Map<String, dynamic> json, StringBuffer buffer) {
  final programmes = json['programmes'] as List<dynamic>;
  for (final raw in programmes) {
    final p = raw as Map<String, dynamic>;
    final id = p['id'] as String;
    final version = p['version'] as int;
    final name = p['name'] as String;
    final birdTypes = jsonEncode(p['bird_types']);
    buffer.writeln(
      "insert into public.programmes (id, name, version, bird_types) "
      "values ('$id', '${name.replaceAll("'", "''")}', $version, '$birdTypes'::jsonb) "
      'on conflict (id) do update set version = excluded.version, name = excluded.name;',
    );
    final steps = p['steps'] as List<dynamic>;
    for (final s in steps) {
      final step = s as Map<String, dynamic>;
      final sid = step['id'] as String;
      final recurring = step['recurring'] == null
          ? 'null'
          : "'${jsonEncode(step['recurring'])}'::jsonb";
      final name = (step['name'] as String).replaceAll("'", "''");
      buffer.writeln(
        "insert into public.programme_steps (id, programme_id, name, age_days, location, optional, "
        "due_window_days_before, due_window_days_after, recurring) values "
        "('$sid', '$id', '$name', ${step['age_days']}, '${step['location']}', "
        "${step['optional'] ?? false}, ${step['due_window_days_before'] ?? 0}, "
        "${step['due_window_days_after'] ?? 0}, $recurring) on conflict (id) do nothing;",
      );
    }
  }
}
